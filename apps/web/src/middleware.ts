import { NextResponse, type NextRequest } from 'next/server';

/**
 * С телефона — в приложение, а не в панель.
 *
 * Домен один, и до сих пор он открывал сотруднику панель на любом экране:
 * директор зашёл с телефона и получил таблицы шириной в монитор. Панель
 * рассчитана на большой экран — отчёты, журнал, ведомости, — а телефону
 * отвечает приложение по адресу `/app/`, то же самое, что стоит APK'ом.
 *
 * Витрина (`/`) не трогается: это страница для клиентов, и с телефона она
 * должна открываться именно витриной.
 *
 * Панель на телефоне всё же иногда нужна (глянуть отчёт, когда компьютера
 * рядом нет), поэтому переадресацию снимает `?panel` в адресе — один раз
 * на переход, без настроек и без куки.
 */

/**
 * Телефон, а не планшет.
 *
 * iPad и Android-планшеты показывают панель сносно, и отправлять их в
 * приложение значило бы отнимать отчёты у того, кто специально взял
 * большой экран.
 */
const PHONE = /Android.+Mobile|iPhone|iPod|Windows Phone|BlackBerry/i;

export function middleware(request: NextRequest): NextResponse {
  if (request.nextUrl.searchParams.has('panel')) return NextResponse.next();
  if (!PHONE.test(request.headers.get('user-agent') ?? '')) return NextResponse.next();

  /*
    Адрес собирается обычным `URL`, а не `nextUrl.clone()`: тот приводит
    путь к настройкам маршрутизации и роняет хвостовой слэш, а он здесь
    значащий — service worker приложения управляет только страницами
    внутри `/app/`, и без слэша браузер не предложит установку.
  */
  return NextResponse.redirect(new URL('/app/', request.url));
}

export const config = {
  /*
    Всё, кроме витрины, самого приложения и служебных путей.

    `/trpc`, `/files` и `/health` уезжают в API соседними правилами
    `next.config.ts` — переадресовать их значило бы оборвать приложению
    связь с сервером. Пути с точкой в имени — файлы (`logo.png`), их тоже
    не трогаем. Корень исключён тем, что после слэша требуется хотя бы
    один символ.
  */
  matcher: ['/((?!app|_next|trpc|files|health|.*\\.).+)'],
};
