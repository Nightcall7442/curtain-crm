import type { NextConfig } from 'next';

/**
 * Пакеты монорепозитория подключаются исходниками, без шага сборки,
 * поэтому Next должен транспилировать их сам.
 *
 * `@curtain-crm/api` здесь нужен ТОЛЬКО ради типа `AppRouter`. Он импортируется
 * через `import type` и стирается компилятором, поэтому Hono, Drizzle и драйвер
 * postgres в клиентский бандл не попадают.
 */
const nextConfig: NextConfig = {
  reactStrictMode: true,
  transpilePackages: ['@curtain-crm/shared'],

  typescript: {
    // Сборка обязана падать на ошибках типов: молча собранная панель
    // с рассинхронизированным контрактом хуже, чем красная сборка.
    ignoreBuildErrors: false,
  },
  eslint: {
    ignoreDuringBuilds: false,
  },

  /**
   * Адрес API вшивается в бандл на этапе сборки: переменные `NEXT_PUBLIC_*`
   * в браузер иначе не попадают.
   *
   * В проде по умолчанию — ОТНОСИТЕЛЬНЫЙ `/trpc`. Панель и API стоят за одним
   * обратным прокси на одном домене, поэтому браузер обращается туда же,
   * откуда пришла страница: образ не привязан к домену, а CORS в проде
   * не участвует вовсе.
   *
   * Значение именно по умолчанию, а не передаётся снаружи, потому что путь
   * с ведущим слэшем плохо переживает дорогу: Git Bash на Windows подменяет
   * `/trpc` на `C:/Program Files/Git/trpc` ещё до запуска сборки. Поймано
   * на прогоне продовой топологии — панель уходила запрашивать `file:///…`.
   *
   * Переопределить всё ещё можно — например, если панель переедет
   * на отдельный поддомен.
   */
  env: {
    NEXT_PUBLIC_API_URL:
      process.env['NEXT_PUBLIC_API_URL'] ??
      (process.env.NODE_ENV === 'production' ? '/trpc' : 'http://localhost:3000/trpc'),
  },

  /**
   * Проксирование API, когда обратного прокси перед приложениями нет.
   *
   * На своём сервере запросы разводит Caddy (см. `Caddyfile`), и эти правила
   * не нужны — `API_INTERNAL_URL` там не задаётся. На платформах вроде Railway
   * домен привязывается к ОДНОМУ сервису и маршрутизации по путям нет, поэтому
   * роль прокси берёт на себя сама панель: браузер и мобильное приложение
   * ходят на один домен, а `/trpc` и `/files` уезжают во внутренний адрес API.
   *
   * Набор путей повторяет `Caddyfile` намеренно: две разные топологии должны
   * вести себя одинаково, иначе ошибку, воспроизводимую только в проде, будет
   * не с чем сравнить.
   *
   * ВАЖНО: `rewrites()` вычисляется на этапе СБОРКИ — Next записывает готовые
   * адреса в `routes-manifest.json`, и при старте берёт их оттуда. Значит,
   * `API_INTERNAL_URL` обязана быть видна во время `next build`, а её смена
   * требует пересборки панели, а не перезапуска.
   */
  async rewrites() {
    const target = process.env['API_INTERNAL_URL'];

    if (target === undefined || target.length === 0) return [];

    // Хвостовой слэш в переменной сделал бы `//trpc` — адрес, на котором
    // часть прокси отвечает 404, а часть молча схлопывает. Убираем заранее.
    const base = target.replace(/\/+$/, '');

    return [
      { source: '/trpc/:path*', destination: `${base}/trpc/:path*` },
      { source: '/files/:path*', destination: `${base}/files/:path*` },
      { source: '/health', destination: `${base}/health` },
    ];
  },
};

export default nextConfig;
