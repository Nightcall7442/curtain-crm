#!/bin/sh
set -e

# Точка входа контейнера API.
#
# Существует ради одной строки — `chown` на каталоге хранилища. Права,
# выставленные в Dockerfile, до тома НЕ доживают: платформа монтирует его
# поверх каталога из образа уже после сборки, и на Railway том принадлежит
# root. Пользователь `node` после этого не может создать в нём даже
# подкаталог, и первая же загрузка фото падает с `EACCES: mkdir`.
#
# В docker-compose дефект не проявлялся: именованный том Docker наследует
# владельца каталога из образа, поэтому локально всё работало, а на проде
# не работало ни разу.
#
# Контейнер стартует от root ровно до этой строки и сразу спускается к
# `node` через `su-exec`: код приложения, до которого дотягиваются загрузки
# из интернета, root'ом не выполняется никогда.
if [ -n "$STORAGE_DISK_PATH" ]; then
  mkdir -p "$STORAGE_DISK_PATH"
  chown -R node:node "$STORAGE_DISK_PATH"
fi

exec su-exec node "$@"
