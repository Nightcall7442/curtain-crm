/**
 * Строка журнала запросов без строки запроса (`?…`).
 *
 * tRPC шлёт вход query-процедур в адресе: у `display.board` там токен ссылки
 * ТВ, у раздачи файлов — подпись ссылки. Журнал читают все, у кого есть доступ
 * к логам хостинга, и секрет в нём перестаёт быть секретом: хеш токена в базе
 * ничего не стоит, если сам токен лежит в логе. Путь и код ответа для
 * разбора инцидентов остаются.
 */
export function withoutQuery(line: string): string {
  return line.replace(/\?\S*/g, '');
}
