/**
 * Часы приложения — по серверу, а не по телефону.
 *
 * Таймеры смены, отлучки и выезда считают «сколько прошло» от момента,
 * записанного сервером. Если брать «сейчас» с часов телефона, ошибка его
 * часов попадает прямо в таймер: айфон с поясом Тихоокеанского времени и
 * часами, выставленными вручную по Ташкенту, живёт на 13 часов впереди, и
 * только что открытая смена показывала «13:00:29».
 *
 * Сервер кладёт свои часы в заголовок `X-Server-Time` каждого ответа API
 * (см. `apps/api/src/index.ts`); `authFetch` передаёт их сюда. Поправка —
 * разница между часами сервера и серединой запроса по часам телефона: так
 * время в пути делится пополам, и поправка не зависит от того, медленная
 * связь или быстрая.
 */

let offsetMs = 0;

/** Отметка сервера пришла: запоминаем, насколько часы телефона расходятся с ним. */
export function noteServerTime(header: string | null, sentAt: number, receivedAt: number): void {
  if (header === null) return;
  const serverMs = Number(header);
  if (!Number.isFinite(serverMs) || serverMs <= 0) return;
  offsetMs = serverMs - (sentAt + receivedAt) / 2;
}

/** «Сейчас» по часам сервера, в миллисекундах эпохи — замена `Date.now()` для таймеров. */
export function serverNow(): number {
  return Date.now() + offsetMs;
}
