-- Обнуление кассы: всё, что было до сегодня, — перенос.
--
-- Владелец открыл кассу и увидел 11,6 млн в ящике и 17,8 млн на счёте —
-- следы проверок, которыми систему гоняли до запуска. Он попросил обнулить:
-- счёт должен пойти с нуля с первого настоящего дня работы.
--
-- Строки не удаляются, а помечаются переносом (`opening`): такая проводка не
-- считается ни в кассе, ни на счёте, ни «на руках», но остаётся в истории
-- заказа и в «оплачено» — это делает триггер, которому пометка безразлична.
-- Вернуть всё обратно можно одним `UPDATE ... SET opening = false`.
--
-- Разовая правка данных, не схемы: на чистой базе трогать нечего, и
-- миграция там ничего не делает.
UPDATE "payments" SET "opening" = true WHERE NOT "opening";
