DELETE FROM "discipline_events";--> statement-breakpoint

-- Расчёты зарплаты. Условия оплаты (оклад, процент, ставки) остаются.
DELETE FROM "payroll_records";--> statement-breakpoint

-- Доп. работы; переписка по ним уходит каскадом.
DELETE FROM "tasks";--> statement-breakpoint

-- Журнал действий: он весь про проверку, первая настоящая запись должна
-- его открывать.
DELETE FROM "audit_log";--> statement-breakpoint

-- Категории швей, проставленные руками. Расчётная считается из рейтинга
-- за прошлый месяц и обнулится сама.
UPDATE "users" SET "sewer_category" = NULL WHERE "sewer_category" IS NOT NULL;--> statement-breakpoint

-- Готовые шторы: остатки в ноль, перечень изделий остаётся.
UPDATE "ready_made_items" SET "quantity" = 0 WHERE "quantity" <> 0;
