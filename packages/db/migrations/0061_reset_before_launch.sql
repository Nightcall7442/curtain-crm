/*
  Копия — в той же базе и до первого удаления.

  Снять дамп снаружи нельзя: у базы нет публичного адреса. Поэтому каждая
  таблица целиком копируется в схему `reset_backup_20260930`: если в
  списке что-то поняли не так, строки возвращаются оттуда обычным
  INSERT ... SELECT. Схему можно удалить, когда станет ясно, что вернуть
  ничего не понадобится.
*/
DO $$
DECLARE
  t record;
BEGIN
  CREATE SCHEMA IF NOT EXISTS reset_backup_20260930;
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS reset_backup_20260930.%I AS TABLE public.%I',
      t.tablename,
      t.tablename
    );
  END LOOP;
END $$;--> statement-breakpoint

-- Деньги — первыми: проводка держит заказ, чек витрины и расчёт зарплаты
-- ограничением `on delete restrict`. Терминальные чеки — тоже проводки.
DELETE FROM "payments";--> statement-breakpoint
-- Строки чеков уходят каскадом.
DELETE FROM "retail_sales";--> statement-breakpoint

-- Уведомления — до расчётов зарплаты: они на них ссылаются.
DELETE FROM "notifications";--> statement-breakpoint

-- Заказы. Каскадом уходят позиции, бригада установки, история статусов,
-- комментарии, фото, проверка упаковки и закупки под заказ; ссылка
-- готового изделия и выезда на заказ обнуляется.
DELETE FROM "orders";--> statement-breakpoint

-- Номер заказа вычисляется из `id` (`DH-000123`): без этого первый заказ
-- после обнуления получил бы следующий номер, а просили с нуля.
ALTER SEQUENCE "orders_id_seq" RESTART WITH 1;--> statement-breakpoint

-- Табель: смены, а каскадом — перерывы и выезды на установку.
DELETE FROM "shifts";--> statement-breakpoint

-- Дисциплина. Своей таблицы у рейтинга нет — он считается из закрытых
