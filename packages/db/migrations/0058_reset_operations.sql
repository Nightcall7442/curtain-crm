-- Обнуление рабочих данных мастерской: заказы, табель, касса, остатки
-- готовых штор, дисциплина и категории швей — с чистого листа.
--
-- Запрошено владельцем: система переходит с обкатки на боевую работу, и
-- накопленные за обкатку цифры мешают — касса показывает выдуманные суммы,
-- рейтинг считается по ненастоящим заказам, номера заказов ушли за триста.
--
-- ЧТО ОСТАЁТСЯ: сотрудники и их роли, филиалы, справочники (ткани, модели,
-- карнизы, позиции закупки), условия оплаты, перечень готовых штор,
-- поручения, выходные, мероприятия и журнал действий.
-- Просили обнулить работу, а не заводить мастерскую заново.
--
-- DELETE, а не TRUNCATE: `TRUNCATE ... CASCADE` опустошает ВСЕ таблицы со
-- ссылками, не разбирая правил, и унёс бы перечень готовых штор, который
-- нужно сохранить. DELETE соблюдает правила внешних ключей: дочерние
-- строки уходят каскадом, а ссылка готового изделия на заказ обнуляется.

-- Деньги — первыми: платёж держит и заказ, и продажу с витрины
-- ограничением `on delete restrict`, и без этого их не удалить.
DELETE FROM "payments";--> statement-breakpoint
DELETE FROM "retail_sale_items";--> statement-breakpoint
DELETE FROM "retail_sales";--> statement-breakpoint

-- Заказы. Каскадом уходят позиции, бригада установки, история статусов,
-- комментарии, фото, проверка упаковки, закупка под заказ и уведомления.
DELETE FROM "orders";--> statement-breakpoint

-- Номер заказа — вычисляемая колонка из `id` (`DH-000123`), отдельного
-- счётчика у него нет. Без этой строки первый заказ после обнуления
-- получил бы номер DH-000347, а просили «с нуля».
ALTER SEQUENCE "orders_id_seq" RESTART WITH 1;--> statement-breakpoint

-- Табель: смены, а каскадом — перерывы и выезды на установку.
DELETE FROM "shifts";--> statement-breakpoint

-- Дисциплина. Своей таблицы у рейтинга нет: он считается из закрытых
-- заказов и этих баллов, поэтому обнуляется вместе с ними.
DELETE FROM "discipline_events";--> statement-breakpoint

-- Расчёты зарплат за прошлые месяцы. Сами УСЛОВИЯ оплаты (оклад, процент,
-- ставка за этап) остаются: это настройка на сотрудника, а не результат
-- работы, и заводить её заново на сорок человек владелец не просил.
DELETE FROM "payroll_records";--> statement-breakpoint

-- Уведомления: без заказов, смен и расчётов они ведут в пустоту.
DELETE FROM "notifications";--> statement-breakpoint

-- Категории швей, проставленные руками. Расчётная считается из рейтинга
-- за прошлый месяц и обнулится сама.
UPDATE "users" SET "sewer_category" = NULL WHERE "sewer_category" IS NOT NULL;--> statement-breakpoint

-- Готовые шторы: остатки в ноль, перечень изделий остаётся — это
-- справочник витрины, заводить его заново незачем.
UPDATE "ready_made_items" SET "quantity" = 0 WHERE "quantity" <> 0;
