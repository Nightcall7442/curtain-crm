import { defineConfig } from 'vitest/config';

/*
  Тесты календарных дат считают «сегодня» по местному времени машины —
  так же, как это делает браузер сотрудника в Ташкенте. На CI машина живёт
  в UTC, и «00:05 по Ташкенту» там ещё вчера. Пояс мастерской задаётся
  явно, чтобы тесты значили одно и то же везде.
*/
process.env['TZ'] = 'Asia/Tashkent';

export default defineConfig({});
